"""Run the original RL scripts or a fresh low-load simulation (Python 2/3)."""
from __future__ import print_function

import argparse
import datetime
import json
import math
import os
import random
import re
import sys

ROOT = '/home/tungthanhle/gem5'
EXAMPLES = ROOT + '/interconnect-routing-gym/example'
SCRIPTS = {
    'qlearning': 'rl_QLearning_example.py',
    'sarsa': 'rl_sarsa_example.py',
    'expected-sarsa': 'rl_expected_sarsa_example.py',
}


def positive_int(value):
    result = int(value)
    if result < 1:
        raise argparse.ArgumentTypeError('must be at least 1')
    return result


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command')
    smoke = commands.add_parser('smoke', help='run a new 8x8, low-load XY simulation')
    smoke.add_argument('--routing', choices=('xy', 'random_oblivious', 'west_first'),
                       default='xy')
    train = commands.add_parser('train', help='run an original RL script')
    train.add_argument('algorithm', choices=sorted(SCRIPTS))
    train.add_argument('--episodes', type=positive_int, default=50)
    train.add_argument('--seed', type=int, default=0,
                       help='Python/NumPy seed; gem5 keeps its original default seed')
    args = parser.parse_args()
    if not args.command:
        parser.error('choose smoke or train')
    return args


def smoke(args):
    # Force the stats to be generated by this invocation, never a previous run.
    for filename in ('stats.txt', 'config.ini', 'config.json'):
        target = '/results/m5out/' + filename
        if os.path.exists(target):
            os.remove(target)
    from icn_gym import icn_routing_gym
    data = icn_routing_gym(0, 0.05, args.routing, 'Mesh_XY')
    for field in ('sim_seconds', 'average_packet_latency', 'flits_received'):
        value = float(data[field][-1])
        if math.isnan(value) or math.isinf(value) or value <= 0:
            raise RuntimeError('Invalid fresh simulation statistic: ' + field)
    expected = {'xy': 1, 'random_oblivious': 2, 'west_first': 3}[args.routing]
    with open('/results/m5out/config.ini') as handle:
        config = handle.read()
    if 'routing_algorithm={}\n'.format(expected) not in config:
        raise RuntimeError('Simulator did not use the requested routing algorithm')
    summary = dict((key, values[-1]) for key, values in data.items())
    with open('/results/smoke-summary.json', 'w') as handle:
        json.dump(summary, handle, indent=2, sort_keys=True)
        handle.write('\n')
    print('SMOKE PASSED: ' + json.dumps(summary, sort_keys=True))


def train(args):
    import numpy
    random.seed(args.seed)
    numpy.random.seed(args.seed)
    filename = EXAMPLES + '/' + SCRIPTS[args.algorithm]
    with open(filename) as handle:
        original = handle.read()
    # Change only the requested run length; preserve learning equations/policy.
    source, count = re.subn(r'(?m)^total_episodes\s*=\s*50\b',
                            'total_episodes = {}'.format(args.episodes), original)
    if count != 1:
        raise RuntimeError('Expected exactly one total_episodes assignment')
    with open('/results/executed_script.py', 'w') as handle:
        handle.write(source)
    with open('/results/executed_icn_gym.py', 'w') as handle:
        with open(EXAMPLES + '/icn_gym.py') as gym_handle:
            handle.write(gym_handle.read())
    context = {'__name__': '__main__', '__file__': filename}
    exec(compile(source, filename, 'exec'), context)


def main():
    args = parse_args()
    os.chdir(ROOT)
    sys.path.insert(0, EXAMPLES)
    # The host helper assigns a new output directory per invocation. Guard direct
    # docker run users against overwriting the same experiment directory.
    try:
        descriptor = os.open('/results/run.json', os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
    except OSError:
        raise RuntimeError('Cannot create run.json; use a new, writable output directory')
    with os.fdopen(descriptor, 'w') as handle:
        record = vars(args).copy()
        record['started_at_utc'] = datetime.datetime.utcnow().isoformat() + 'Z'
        json.dump(record, handle, indent=2, sort_keys=True)
        handle.write('\n')
    if args.command == 'smoke':
        smoke(args)
    else:
        train(args)


if __name__ == '__main__':
    main()
